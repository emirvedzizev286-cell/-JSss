 /**
  * \d - цифра [0 - 9]
  * \w - буквма , цифра , _ [A-Za-z0,9_]
  * \s - пробельный символ
  * \D , \W , \S - отрицание (НЕ ЦИФРА , НЕ БУКВА , НЕ ПРОБЕЛ)
  * . - ЛЮБОЙ СИМВОЛ КРОМЕ ПЕРЕВОДА СТРОКИ
  */

 //квантифакторы (количесство)
 /**
  * + - один и больше
  * * -  ноль и больше
  * ? - ноль или один
  *  {3} -  равно 3
  * {2 , 5 } - от 2 до 5
  * {2, } -  2 и больше
  * 
  */

 //якоря
 // ' - начало строки
 // $ -0 конец строки

 //группа и альтернация
 /**
  * (...) - группа
  * | - или
  * [abc] _  любой из символов a,b,c
  * [^ abc] -  ллюбой кроме a,b,c
  * [a-z] - диапозон
  */

